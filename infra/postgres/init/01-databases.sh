#!/bin/sh
# Una base y un rol por servicio: ningún servicio puede leer la base de otro.
set -e
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname postgres <<-EOSQL
  CREATE ROLE identity LOGIN PASSWORD '$DB_IDENTITY_PASSWORD';
  CREATE DATABASE identity OWNER identity;
  CREATE ROLE projects LOGIN PASSWORD '$DB_PROJECTS_PASSWORD';
  CREATE DATABASE projects OWNER projects;
  CREATE ROLE billing LOGIN PASSWORD '$DB_BILLING_PASSWORD';
  CREATE DATABASE billing OWNER billing;
  CREATE ROLE analytics LOGIN PASSWORD '$DB_ANALYTICS_PASSWORD';
  CREATE DATABASE analytics OWNER analytics;
  CREATE ROLE notifications LOGIN PASSWORD '$DB_NOTIFICATIONS_PASSWORD';
  CREATE DATABASE notifications OWNER notifications;
  CREATE ROLE capacity LOGIN PASSWORD '$DB_CAPACITY_PASSWORD';
  CREATE DATABASE capacity OWNER capacity;
  CREATE ROLE operations LOGIN PASSWORD '$DB_OPERATIONS_PASSWORD';
  CREATE DATABASE operations OWNER operations;
  CREATE ROLE procurement LOGIN PASSWORD '$DB_PROCUREMENT_PASSWORD';
  CREATE DATABASE procurement OWNER procurement;
  REVOKE CONNECT ON DATABASE identity FROM PUBLIC;
  REVOKE CONNECT ON DATABASE projects FROM PUBLIC;
  REVOKE CONNECT ON DATABASE billing FROM PUBLIC;
  REVOKE CONNECT ON DATABASE analytics FROM PUBLIC;
  REVOKE CONNECT ON DATABASE notifications FROM PUBLIC;
  REVOKE CONNECT ON DATABASE capacity FROM PUBLIC;
  REVOKE CONNECT ON DATABASE operations FROM PUBLIC;
  REVOKE CONNECT ON DATABASE procurement FROM PUBLIC;
EOSQL
