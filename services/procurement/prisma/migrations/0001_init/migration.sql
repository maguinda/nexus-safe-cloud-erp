-- Procurement & Inventory: proveedores, artículos, pedidos de compra, sugerencias por avisos de sensores y outbox.
CREATE TABLE "suppliers" (
  "id" UUID NOT NULL DEFAULT gen_random_uuid(),
  "name" TEXT NOT NULL,
  "kind" TEXT NOT NULL,
  "terms" TEXT NOT NULL DEFAULT '',
  "created_at" TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  CONSTRAINT "suppliers_pkey" PRIMARY KEY ("id"),
  CONSTRAINT "suppliers_kind_check" CHECK ("kind" IN ('fixed', 'tender'))
);
CREATE UNIQUE INDEX "suppliers_name_lower_key" ON "suppliers"(lower("name"));

CREATE TABLE "items" (
  "id" UUID NOT NULL DEFAULT gen_random_uuid(),
  "name" TEXT NOT NULL,
  "kind" TEXT NOT NULL,
  "for_kinds" TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
  "on_hand" INTEGER NOT NULL DEFAULT 0,
  "created_at" TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  CONSTRAINT "items_pkey" PRIMARY KEY ("id"),
  CONSTRAINT "items_kind_check" CHECK ("kind" IN ('equipment', 'spare')),
  CONSTRAINT "items_on_hand_check" CHECK ("on_hand" >= 0 AND "on_hand" <= 1000000)
);
CREATE UNIQUE INDEX "items_name_lower_key" ON "items"(lower("name"));

CREATE TABLE "purchase_orders" (
  "id" UUID NOT NULL DEFAULT gen_random_uuid(),
  "number" INTEGER GENERATED BY DEFAULT AS IDENTITY,
  "supplier_id" UUID NOT NULL,
  "item_id" UUID NOT NULL,
  "quantity" INTEGER NOT NULL,
  "unit_price_cop" INTEGER NOT NULL,
  "total_cop" INTEGER NOT NULL,
  "status" TEXT NOT NULL DEFAULT 'ordered',
  "created_at" TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  "received_at" TIMESTAMPTZ(6),
  CONSTRAINT "purchase_orders_pkey" PRIMARY KEY ("id"),
  CONSTRAINT "purchase_orders_status_check" CHECK ("status" IN ('ordered', 'received', 'cancelled')),
  CONSTRAINT "purchase_orders_quantity_check" CHECK ("quantity" BETWEEN 1 AND 100000),
  CONSTRAINT "purchase_orders_total_check" CHECK ("total_cop" = "quantity" * "unit_price_cop" AND "total_cop" <= 2000000000),
  CONSTRAINT "purchase_orders_received_check" CHECK (("status" = 'received') = ("received_at" IS NOT NULL)),
  CONSTRAINT "purchase_orders_supplier_id_fkey" FOREIGN KEY ("supplier_id") REFERENCES "suppliers"("id") ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT "purchase_orders_item_id_fkey" FOREIGN KEY ("item_id") REFERENCES "items"("id") ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE UNIQUE INDEX "purchase_orders_number_key" ON "purchase_orders"("number");
CREATE INDEX "purchase_orders_created_at_idx" ON "purchase_orders"("created_at" DESC);

CREATE TABLE "processed_events" (
  "event_id" UUID NOT NULL,
  "processed_at" TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  CONSTRAINT "processed_events_pkey" PRIMARY KEY ("event_id")
);

CREATE TABLE "alert_suggestions" (
  "id" SERIAL NOT NULL,
  "event_id" UUID NOT NULL,
  "device_name" TEXT NOT NULL,
  "location" TEXT NOT NULL,
  "reading_kind" TEXT NOT NULL,
  "status" TEXT NOT NULL,
  "value" DOUBLE PRECISION NOT NULL,
  "unit" TEXT NOT NULL,
  "occurred_at" TIMESTAMPTZ(6) NOT NULL,
  CONSTRAINT "alert_suggestions_pkey" PRIMARY KEY ("id")
);
CREATE UNIQUE INDEX "alert_suggestions_event_id_key" ON "alert_suggestions"("event_id");
CREATE INDEX "alert_suggestions_occurred_at_idx" ON "alert_suggestions"("occurred_at" DESC);

CREATE TABLE "outbox_events" (
  "id" UUID NOT NULL,
  "aggregate_id" TEXT NOT NULL,
  "type" TEXT NOT NULL,
  "routing_key" TEXT NOT NULL,
  "payload" JSONB NOT NULL,
  "created_at" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "published_at" TIMESTAMP(3),
  CONSTRAINT "outbox_events_pkey" PRIMARY KEY ("id")
);
CREATE UNIQUE INDEX "outbox_events_aggregate_id_type_key" ON "outbox_events"("aggregate_id", "type");
CREATE INDEX "outbox_events_published_at_idx" ON "outbox_events"("published_at");
